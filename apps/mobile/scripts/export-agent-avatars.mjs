#!/usr/bin/env node
// Renders the Agent avatar figures the web serves (apps/web/public/agent-avatars,
// one SVG per figure) into PNGs the phone ships, and writes the figure table
// with their drawn backgrounds. React Native has no SVG renderer without a
// native module, so the phone carries rasters. Run after the web's figures
// change (needs Google Chrome): `node apps/mobile/scripts/export-agent-avatars.mjs`.
import { chromium } from "@playwright/test";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const source = join(root, "apps/web/public/agent-avatars");
const table = readFileSync(
  join(root, "apps/web/src/features/rooms/members/agent-avatar.ts"),
  "utf8",
);
const figures = /const AGENT_FIGURES = `([^`]*)`/
  .exec(table)?.[1]
  .trim()
  .split(/\s+/)
  .map((entry) => entry.split(":"));
if (!figures?.length) throw new Error("AGENT_FIGURES not found");

const assets = join(root, "apps/mobile/assets/agent-avatars");
rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });
// A browser renders each SVG at 3x a 64pt tile with a transparent
// background, so the tile's own color shows through.
const browser = await chromium.launch({ channel: "chrome" });
try {
  const page = await browser.newPage({
    viewport: { width: 64, height: 64 },
    deviceScaleFactor: 3,
  });
  for (const [name] of figures) {
    const svg = readFileSync(join(source, `${name}.svg`), "utf8");
    await page.setContent(
      `<style>html,body{margin:0;background:transparent}svg{width:64px;height:64px;display:block}</style>${svg}`,
    );
    await page.screenshot({
      path: join(assets, `${name}.png`),
      omitBackground: true,
    });
  }
} finally {
  await browser.close();
}

const header =
  "// Generated by scripts/export-agent-avatars.mjs from the web's figures; do not edit.\n";
writeFileSync(
  join(root, "apps/mobile/src/ui/agent-figures.generated.ts"),
  `${header}/** Each figure in gallery order with the background it was drawn on. */
export const AGENT_FIGURES: readonly (readonly [string, string])[] = [
${figures.map(([name, color]) => `  ["${name}", "${color}"],`).join("\n")}
];
`,
);
writeFileSync(
  join(root, "apps/mobile/src/ui/agent-figure-images.generated.ts"),
  `${header}/* eslint-disable @typescript-eslint/no-require-imports */
/** Each figure's image, for React Native's asset system. */
export const AGENT_FIGURE_IMAGES: Readonly<Record<string, number>> = {
${figures.map(([name]) => `  ${name}: require("../../assets/agent-avatars/${name}.png"),`).join("\n")}
};
`,
);
process.stdout.write(`${figures.length} figures\n`);
