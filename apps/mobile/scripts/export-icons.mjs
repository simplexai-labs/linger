#!/usr/bin/env node
// Renders the Hugeicons the web uses (the same icon for the same job, from
// the web's own @hugeicons/core-free-icons) into black template PNGs; the app
// tints them with Image's tintColor. Like the web's <Icon>, each icon comes in
// two strokes: 2 for 16px and below, 1.5 from 20px. React Native has no SVG
// renderer without a native module. Needs Google Chrome:
// `node apps/mobile/scripts/export-icons.mjs`.
import { chromium } from "@playwright/test";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../..", import.meta.url));
const hugeicons = createRequire(join(root, "apps/web/package.json"))(
  "@hugeicons/core-free-icons",
);

/** App name → the Hugeicon the web shows for the same thing. */
const icons = {
  sidebar: "SidebarLeftIcon",
  menu: "Menu01Icon",
  add: "PlusSignIcon",
  mic: "Mic01Icon",
  micOff: "MicOff01Icon",
  send: "ArrowUp02Icon",
  stop: "StopIcon",
  close: "Cancel01Icon",
  check: "Tick02Icon",
  chevron: "ArrowRight01Icon",
  messages: "Message01Icon",
  library: "LibrariesIcon",
  wiki: "BookOpen01Icon",
  record: "AiTranscribeAudioIcon",
  settings: "Settings01Icon",
  wave: "AudioWave01Icon",
  play: "PlayIcon",
  pause: "PauseIcon",
  back15: "GoBackward15SecIcon",
  forward15: "GoForward15SecIcon",
  page: "Note01Icon",
  open: "SquareArrowUpRightIcon",
  file: "File01Icon",
  filePdf: "Pdf02Icon",
  fileSlides: "Ppt02Icon",
  fileDoc: "Doc02Icon",
  fileSheet: "FileSpreadsheetIcon",
  fileCode: "FileCodeIcon",
  fileImage: "FileImageIcon",
  fileAudio: "FileAudioIcon",
  fileVideo: "FileVideoIcon",
  fileArchive: "FileZipIcon",
  laptop: "LaptopIcon",
  notification: "Notification01Icon",
  info: "InformationCircleIcon",
  securityCheck: "SecurityCheckIcon",
  camera: "Camera01Icon",
  link: "Link01Icon",
  photo: "Image01Icon",
  attachment: "Attachment01Icon",
  upload: "CloudUploadIcon",
  share: "Share08Icon",
};

const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function svg(nodes, strokeWidth) {
  const body = nodes
    .map(([tag, attrs]) => {
      const parts = Object.entries(attrs)
        .filter(([key]) => key !== "key")
        .map(([key, value]) => {
          const v =
            key === "strokeWidth"
              ? strokeWidth
              : String(value).replace("currentColor", "#000");
          return `${kebab(key)}="${v}"`;
        });
      return `<${tag} ${parts.join(" ")}/>`;
    })
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">${body}</svg>`;
}

const assets = join(root, "apps/mobile/assets/icons");
rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });
const browser = await chromium.launch({ channel: "chrome" });
try {
  const page = await browser.newPage({
    viewport: { width: 24, height: 24 },
    deviceScaleFactor: 3,
  });
  for (const [name, source] of Object.entries(icons)) {
    const nodes = hugeicons[source];
    if (!nodes)
      throw new Error(`${source} is not in @hugeicons/core-free-icons`);
    for (const [suffix, stroke] of [
      ["", 1.5],
      ["-bold", 2],
    ]) {
      await page.setContent(
        `<style>html,body{margin:0;background:transparent}svg{display:block}</style>${svg(nodes, stroke)}`,
      );
      await page.screenshot({
        path: join(assets, `${name}${suffix}.png`),
        omitBackground: true,
      });
    }
  }
} finally {
  await browser.close();
}
const entries = Object.keys(icons).map(
  (name) =>
    `  ${name}: {\n    regular: require("../../assets/icons/${name}.png"),\n    bold: require("../../assets/icons/${name}-bold.png"),\n  },`,
);
writeFileSync(
  join(root, "apps/mobile/src/ui/icon-images.generated.ts"),
  `// Generated by scripts/export-icons.mjs from the web's Hugeicons; do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */
export const ICON_IMAGES = {
${entries.join("\n")}
} as const;
`,
);
process.stdout.write(`${Object.keys(icons).length} icons\n`);
